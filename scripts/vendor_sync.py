import argparse
import configparser
import hashlib
import re
import subprocess
import sys
import tomllib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PACKAGES = {"glint": "src", "glint_markdown": "dev"}
NAMESPACE = "licence_audit/internal/vendor"
SUFFIXES = {".gleam", ".erl", ".hrl", ".mjs", ".js"}
EXIT_DECLARATIONS = """@external(erlang, "glint_markdown_exit_ffi", "stderr")
@external(javascript, "./exit_ffi.mjs", "stderr")
pub fn stderr(message message: String) -> Nil

@external(erlang, "glint_markdown_exit_ffi", "exit_with")
@external(javascript, "./exit_ffi.mjs", "exit_with")
pub fn exit_with(code code: Int) -> Nil
"""
EXIT_REPLACEMENT = """import gleam/io

pub fn stderr(message message: String) -> Nil {
  io.print_error(message)
}

@external(erlang, "erlang", "halt")
@external(javascript, "node:process", "exit")
pub fn exit_with(code code: Int) -> Nil
"""
EXIT_NATIVE_FILES = {
    "glint_markdown/internal/glint_markdown_exit_ffi.erl": """-module(glint_markdown_exit_ffi).
-export([stderr/1, exit_with/1]).

stderr(Message) ->
    io:put_chars(standard_error, Message),
    nil.

exit_with(Code) ->
    erlang:halt(Code),
    nil.
""",
    "glint_markdown/internal/exit_ffi.mjs": """export function stderr(message) {
  process.stderr.write(message);
  return undefined;
}

export function exit_with(code) {
  process.exit(code);
  return undefined;
}
""",
}
DEVELOPMENT_NATIVE_FILES = {
    "glint_markdown_filesystem_ffi.erl": "69c746ac62a726ecb6cdd21b138e4173d7614e25a20e8dacf148c2181650808e",
    "glint_markdown/internal/filesystem_ffi.mjs": "bd08948e32cb555b6298d2ffb017e1c369b02dda322adca9a6721e8153822313",
}


def rewrite_source(
    text: str, suffix: str, modules: dict[str, str], ffi: dict[str, str]
) -> str:
    if suffix == ".gleam":
        text = re.sub(
            r"(?m)^(import\s+)([a-z][a-z0-9_]*(?:/[a-z][a-z0-9_]*)*)",
            lambda match: match[1] + modules.get(match[2], match[2]),
            text,
        )
        return re.sub(
            r'(@external\(erlang,\s*")([a-z][a-z0-9_]*)(")',
            lambda match: match[1] + ffi.get(match[2], match[2]) + match[3],
            text,
        )
    if suffix == ".erl":
        for original, renamed in ffi.items():
            text = re.sub(
                rf"(?m)^-module\({re.escape(original)}\)\.",
                f"-module({renamed}).",
                text,
            )
            text = re.sub(rf"\b{re.escape(original)}:", f"{renamed}:", text)
    return text


def format_gleam(text: str) -> str:
    result = subprocess.run(
        ["gleam", "format", "--stdin"],
        input=text,
        text=True,
        capture_output=True,
        check=True,
    )
    return result.stdout


def generated_files(root: Path) -> dict[Path, str]:
    config = tomllib.loads((root / "gleam.toml").read_text())
    sources = []
    modules = {}
    ffi = {}
    notices = [
        "Vendored source notices",
        "Generated by scripts/vendor_sync.py. Do not edit.",
        "",
        "The copies use licence_audit's module namespace and Erlang FFI names.",
        "glint_markdown's exit shim uses gleam/io and native process-exit calls.",
        "Each copied source file identifies its upstream file and commit.",
        "",
    ]
    for package, scope in PACKAGES.items():
        upstream = root / "vendor" / package
        metadata = tomllib.loads((upstream / "gleam.toml").read_text())
        if metadata["name"] != package or metadata["licences"] != ["Apache-2.0"]:
            raise ValueError(f"Review the package name and licence for {upstream}.")
        available = config["dependencies"] | (
            config["dev_dependencies"] if scope == "dev" else {}
        )
        for name, requirement in metadata["dependencies"].items():
            if name in PACKAGES:
                if scope == "src" and PACKAGES[name] != "src":
                    raise ValueError(f"{package} has a development-only dependency: {name}")
            elif name not in available or not isinstance(requirement, str):
                raise ValueError(
                    f"Declare {package}'s Hex dependency {name} in gleam.toml."
                )
        provenance = configparser.ConfigParser(interpolation=None)
        provenance.read_string((upstream / ".gitrepo").read_text())
        commit = provenance["subrepo"]["commit"]
        if not re.fullmatch(r"[a-f0-9]{40}", commit):
            raise ValueError(f"Invalid upstream commit in {upstream / '.gitrepo'}.")
        source_paths = sorted((upstream / "src").rglob("*"))
        if not any(path.suffix == ".gleam" for path in source_paths):
            raise ValueError(f"No Gleam sources in {upstream / 'src'}.")
        for path in source_paths:
            if path.is_symlink():
                raise ValueError(f"Vendored sources must not be symlinks: {path}")
            if not path.is_file():
                continue
            if path.suffix not in SUFFIXES:
                raise ValueError(f"Unsupported vendored source file: {path}")
            relative = path.relative_to(upstream / "src")
            if package == "glint_markdown" and relative.as_posix() in EXIT_NATIVE_FILES:
                if path.read_text() != EXIT_NATIVE_FILES[relative.as_posix()]:
                    raise ValueError(f"Review the updated development exit shim: {path}")
                continue
            destination_scope = scope
            if scope == "dev" and path.suffix in {".erl", ".hrl", ".mjs", ".js"}:
                expected = DEVELOPMENT_NATIVE_FILES.get(relative.as_posix())
                if package != "glint_markdown" or expected is None:
                    raise ValueError(f"Review native development sources that can ship in production: {path}")
                if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
                    raise ValueError(f"Review the updated native development source: {path}")
                if path.suffix == ".erl":
                    destination_scope = "native/dev"
            destination = Path(destination_scope) / NAMESPACE / relative
            if path.suffix == ".gleam":
                original = relative.with_suffix("").as_posix()
                if original in modules:
                    raise ValueError(f"Duplicate vendored module: {original}")
                modules[original] = f"{NAMESPACE}/{original}"
            elif path.suffix == ".erl":
                original = path.stem
                if original in ffi:
                    raise ValueError(f"Duplicate Erlang FFI module: {original}")
                ffi[original] = f"licence_audit_vendor_{original}"
                destination = destination.with_name(ffi[original] + ".erl")
            sources.append((path, destination, commit))
        notices.extend(
            [
                f"{package} {metadata['version']} ({'runtime' if scope == 'src' else 'development only'})",
                f"Source: {provenance['subrepo']['remote']}",
                f"Commit: {commit}",
                "Licence: Apache-2.0",
                "",
            ]
        )
        for name in ("NOTICE", "NOTICE.txt", "NOTICE.md"):
            notice = upstream / name
            if notice.exists():
                notices.extend([notice.read_text().rstrip(), ""])

    generated = {}
    for source, destination, commit in sources:
        text = source.read_text()
        if source.suffix in {".mjs", ".js"}:
            runtime = "../" * (len(destination.parts) - 2) + "gleam.mjs"
            text = text.replace('"../../gleam.mjs"', f'"{runtime}"')
        if source.relative_to(root).as_posix() == "vendor/glint_markdown/src/glint_markdown/internal/exit.gleam":
            if text.count(EXIT_DECLARATIONS) != 1:
                raise ValueError(f"Review the updated development exit declarations: {source}")
            text = text.replace(EXIT_DECLARATIONS, EXIT_REPLACEMENT)
        marker = "%" if source.suffix in {".erl", ".hrl"} else "//"
        text = (
            f"{marker} Vendored from {source.relative_to(root)} at {commit}.\n"
            f"{marker} Modified for licence_audit vendoring. Run just vendor-sync to update.\n"
        ) + rewrite_source(text, source.suffix, modules, ffi)
        if source.suffix == ".gleam":
            text = format_gleam(text)
        generated[destination] = text

    # Both upstream packages declare Apache-2.0; glint_markdown has no licence file.
    notices.extend([(root / "vendor/glint/LICENSE").read_text().rstrip(), ""])
    generated[Path("NOTICE")] = "\n".join(notices)
    return generated


def sync(root: Path, check: bool) -> list[Path]:
    generated = generated_files(root)
    existing = {Path("NOTICE")} if (root / "NOTICE").exists() else set()
    for scope in set(PACKAGES.values()) | {"native/dev"}:
        directory = root / scope / NAMESPACE
        existing.update(
            path.relative_to(root) for path in directory.rglob("*") if path.is_file()
        )
    changed = []
    for relative in sorted(existing | generated.keys()):
        path = root / relative
        if path.is_symlink() or any(parent.is_symlink() for parent in path.parents):
            raise ValueError(f"Vendoring output must not use symlinks: {path}")
        expected = generated.get(relative)
        if expected is None:
            changed.append(relative)
            if not check:
                path.unlink()
        elif not path.exists() or path.read_text() != expected:
            changed.append(relative)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync namespaced vendored Gleam sources.")
    parser.add_argument("--check", action="store_true", help="Report drift without writing files.")
    args = parser.parse_args()
    try:
        changed = sync(ROOT, args.check)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"Vendoring failed: {error}", file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError):
            print(error.stderr, file=sys.stderr)
        return 1
    if changed:
        print("\n".join(str(path) for path in changed))
        if args.check:
            print("Vendored sources differ. Run just vendor-sync.", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
